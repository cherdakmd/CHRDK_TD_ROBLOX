#!/usr/bin/env python3
"""Build a self-contained Roblox Studio place from the Rojo source tree.

No Roblox credentials, network access, or third-party Python packages required.
The resulting .rbxlx contains only scripts; the map is generated by the server.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


class PlaceBuilder:
    def __init__(self) -> None:
        self.counter = 0
        self.roblox = ET.Element("roblox", {"version": "4", "xmlns:xmime": "http://www.roblox.com/2005/5/xmlmime"})
        self.model = self.item(self.roblox, "DataModel")
        props = self.properties(self.model)
        self.prop(props, "string", "Name", "CHRDK — РУБЕЖ")

    def item(self, parent: ET.Element, class_name: str, name: str | None = None) -> ET.Element:
        element = ET.SubElement(parent, "Item", {"class": class_name, "referent": f"RBX{self.counter}"})
        self.counter += 1
        if name is not None:
            self.prop(self.properties(element), "string", "Name", name)
        return element

    @staticmethod
    def properties(element: ET.Element) -> ET.Element:
        props = element.find("Properties")
        if props is None:
            props = ET.SubElement(element, "Properties")
        return props

    @staticmethod
    def prop(props: ET.Element, kind: str, name: str, value: object) -> ET.Element:
        node = ET.SubElement(props, kind, {"name": name})
        node.text = str(value)
        return node

    def service(self, class_name: str) -> ET.Element:
        return self.item(self.model, class_name, class_name)

    def folder(self, parent: ET.Element, name: str) -> ET.Element:
        return self.item(parent, "Folder", name)

    def script(self, parent: ET.Element, path: Path) -> None:
        if path.name.endswith(".server.luau"):
            class_name, name = "Script", path.name[:-12]
        elif path.name.endswith(".client.luau"):
            class_name, name = "LocalScript", path.name[:-12]
        else:
            class_name, name = "ModuleScript", path.stem
        element = self.item(parent, class_name, name)
        props = self.properties(element)
        source = path.read_text(encoding="utf-8")
        self.prop(props, "ProtectedString", "Source", source)
        if class_name == "Script":
            self.prop(props, "bool", "Enabled", "true")

    def tree(self, parent: ET.Element, directory: Path) -> None:
        for path in sorted(directory.iterdir()):
            if path.is_dir():
                self.tree(self.folder(parent, path.name), path)
            elif path.suffix == ".luau":
                self.script(parent, path)

    def build(self) -> ET.Element:
        workspace = self.service("Workspace")
        props = self.properties(workspace)
        self.prop(props, "bool", "FilteringEnabled", "true")
        self.prop(props, "bool", "StreamingEnabled", "false")
        self.service("Players")
        lighting = self.service("Lighting")
        props = self.properties(lighting)
        self.prop(props, "float", "ClockTime", 14.5)
        self.prop(props, "float", "Brightness", 2.3)
        self.prop(props, "bool", "GlobalShadows", "true")
        replicated = self.service("ReplicatedStorage")
        self.tree(self.folder(replicated, "Shared"), ROOT / "src/shared")
        server = self.service("ServerScriptService")
        self.tree(self.folder(server, "Server"), ROOT / "src/server")
        starter = self.service("StarterPlayer")
        scripts = self.item(starter, "StarterPlayerScripts", "StarterPlayerScripts")
        self.tree(self.folder(scripts, "Client"), ROOT / "src/client")
        self.service("StarterGui")
        self.service("StarterPack")
        sound = self.service("SoundService")
        self.prop(self.properties(sound), "bool", "RespectFilteringEnabled", "true")
        self.service("TextChatService")
        ET.SubElement(self.roblox, "External").text = "null"
        ET.SubElement(self.roblox, "SharedStrings")
        ET.indent(self.roblox, space="  ")
        return self.roblox


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "release/CHRDK_Rubezh.rbxlx")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    tree = PlaceBuilder().build()
    ET.ElementTree(tree).write(args.output, encoding="utf-8", xml_declaration=True)
    scripts = sum(1 for _ in (ROOT / "src").rglob("*.luau"))
    print(f"Built {args.output.relative_to(ROOT)} ({args.output.stat().st_size:,} bytes, {scripts} Luau scripts)")


if __name__ == "__main__":
    main()
